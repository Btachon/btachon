/**
 * Returns today's daily focus based on day of the month (1–31, rotating).
 */
export function getDailyFocus(): DailyFocus {
  const dayOfMonth = new Date().getDate(); // 1–31
  return DAILY_FOCUSES.find((f) => f.day === dayOfMonth) ?? DAILY_FOCUSES[0];
}

/**
 * Returns the focus for a given date.
 */
export function getFocusForDate(date: Date): DailyFocus {
  const day = date.getDate();
  return DAILY_FOCUSES.find((f) => f.day === day) ?? DAILY_FOCUSES[0];
}
